def main():
    schools = [s.strip() for s in raw_list.split('\n') if s.strip()]
    counter = Counter(schools)
    
    print(f"Total students: {len(schools)}")
    print(f"Unique middle schools: {len(counter)}")
    print("\n--- Middle School Rankings ---")
    
    # Sort by count descending, then by school name alphabetically
    sorted_schools = sorted(counter.items(), key=lambda x: (-x[1], x[0]))
    for school, count in sorted_schools:
        print(f"{school}: {count}명")

if __name__ == '__main__':
    main()
